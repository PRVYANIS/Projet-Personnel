import sharp from 'sharp';
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const inputDirectory = resolve(projectRoot, 'public/images');
const outputDirectory = resolve(projectRoot, 'public/site/media');
const manifestPath = resolve(projectRoot, 'src/data/images.js');

// Stable ASCII names are independent from the original, descriptive filenames.
// These illustrations are not references to projects completed by the practice.
const sources = [
  {
    id: 'residence',
    file: 'Résidence contemporaine à l’heure bleue-1.png',
    hero: true,
    alt: 'Illustration IA de résidences contemporaines à l’heure bleue, avec façades claires et balcons éclairés.',
  },
  {
    id: 'structure',
    file: 'Ossature résidentielle en béton armé-3.png',
    alt: 'Illustration IA d’une ossature résidentielle en béton armé montrant poteaux, poutres et circulations verticales.',
  },
  {
    id: 'maquette',
    file: 'Maquette architecturale de trois blocs résidentiels-4.png',
    alt: 'Illustration IA d’une maquette de trois bâtiments résidentiels organisés autour d’espaces paysagers.',
  },
  {
    id: 'plan',
    file: 'Plan d’étage résidentiel à quatre logements-5.png',
    alt: 'Illustration IA d’un plan d’étage de quatre logements distribués autour d’un noyau de circulation central.',
  },
  {
    id: 'lotissement',
    file: 'Lotissement résidentiel méditerranéen vu du ciel-2.png',
    alt: 'Illustration IA en vue aérienne d’un ensemble résidentiel méditerranéen mêlant immeubles, villas et espaces plantés.',
  },
  {
    id: 'villaAxono',
    slug: 'villa-axono',
    file: 'Maquette axonométrique d’une villa méditerranéenne-2.png',
    alt: 'Illustration IA d’une maquette axonométrique de villa en L, avec terrasse et olivier au centre de la cour.',
  },
  {
    id: 'villaCour',
    slug: 'villa-cour',
    file: 'Villa méditerranéenne en L, cour à l’olivier-3.png',
    alt: 'Illustration IA en vue de dessus du plan d’une villa en L, avec trois chambres et une cour autour d’un olivier.',
  },
  {
    id: 'villaOlivier',
    slug: 'villa-olivier',
    file: "Villa méditerranéenne autour d'un olivier-1.png",
    alt: 'Illustration IA d’une villa méditerranéenne de plain-pied ouverte sur un olivier et un jardin au soleil couchant.',
  },
];

await mkdir(outputDirectory, { recursive: true });
await mkdir(dirname(manifestPath), { recursive: true });

const images = {};
let totalBytes = 0;

for (const source of sources) {
  const input = resolve(inputDirectory, source.file);
  const metadata = await sharp(input).metadata();
  const rotated = metadata.orientation >= 5 && metadata.orientation <= 8;
  const width = rotated ? metadata.height : metadata.width;
  const height = rotated ? metadata.width : metadata.height;

  if (!width || !height) {
    throw new Error(`Dimensions introuvables pour ${source.file}`);
  }

  // Cap each requested size to the source width: no original is ever enlarged.
  // Only the hero may receive the optional 1920px variant.
  const requestedWidths = source.hero ? [640, 1280, 1920] : [640, 1280];
  const widths = [...new Set(requestedWidths.map((size) => Math.min(size, width)))];
  const variants = [];

  for (const targetWidth of widths) {
    const basename = `${source.slug ?? source.id}-${targetWidth}`;
    const webpName = `${basename}.webp`;
    const avifName = `${basename}.avif`;
    const [webp, avif] = await Promise.all([
      sharp(input)
        .rotate()
        .resize({ width: targetWidth, withoutEnlargement: true })
        .webp({ quality: 82, effort: 4 })
        .toFile(resolve(outputDirectory, webpName)),
      sharp(input)
        .rotate()
        .resize({ width: targetWidth, withoutEnlargement: true })
        .avif({ quality: 50, effort: 4 })
        .toFile(resolve(outputDirectory, avifName)),
    ]);

    if (webp.width !== targetWidth || avif.width !== targetWidth) {
      throw new Error(`Largeur de sortie inattendue pour ${source.file}`);
    }

    totalBytes += webp.size + avif.size;
    variants.push({ width: webp.width, webp: `/media/${webpName}`, avif: `/media/${avifName}` });
  }

  const fallback = variants.find((variant) => variant.width === Math.min(1280, width));
  images[source.id] = {
    id: source.id,
    src: fallback.webp,
    srcSet: variants.map((variant) => `${variant.webp} ${variant.width}w`).join(', '),
    avifSrcSet: variants.map((variant) => `${variant.avif} ${variant.width}w`).join(', '),
    width,
    height,
    alt: source.alt,
  };
  console.log(`${source.id}: ${width}×${height} → ${widths.join(', ')} px, WebP + AVIF`);
}

const manifest = `// Generated by scripts/optimize-images.mjs. Original illustrations remain in public/images.\nexport const images = ${JSON.stringify(images, null, 2)};\n`;
await writeFile(manifestPath, manifest, 'utf8');
console.log(`Images optimisées : ${(totalBytes / 1024 / 1024).toFixed(2)} Mo. Manifest : src/data/images.js`);
